<p class="lead-p">Jejak perubahan untuk audit.</p>
<h3>Siapa bisa melihat</h3>
<ul>
    <li><b>Petugas bidang</b>: riwayat data input bidangnya sendiri.</li>
    <li><b>Pemeliharaan</b> dan <b>Manajemen</b>: riwayat data input semua bidang.</li>
    <li><b>Admin</b>: semua, termasuk tab Data master dan Login.</li>
</ul>
<h3>Isi tiap tab</h3>
<dl>
    <dt>Data input</dt><dd>Siapa mengubah angka apa, dari berapa ke berapa, kapan.</dd>
    <dt>Data master</dt><dd>Perubahan kendaraan, jenis, bidang, dan akun. Isi password tidak pernah dicatat.</dd>
    <dt>Login</dt><dd>Masuk, keluar, keluar otomatis, dan percobaan gagal, beserta perangkat dan IP.</dd>
</dl>
