<p class="lead-p">Isi jam operasional setiap kendaraan untuk satu tanggal. Total satu kendaraan selalu 24 jam.</p>
<h3>Cara mengisi</h3>
<ol>
    <li>Pilih tanggal.</li>
    <li>Isi Jalan, Rusak, Perbaikan, PM (angka bulat 0–24). Kolom bergembok bukan bagian Anda.</li>
    <li>Standby terisi otomatis: 24 − (Jalan + Rusak + Perbaikan + PM).</li>
    <li>Klik <b>Simpan</b> atau <kbd>Ctrl</kbd>+<kbd>S</kbd>. Baris kuning = belum disimpan.</li>
</ol>
<p>Setiap hari semua kendaraan aktif otomatis tercatat <b>Standby 24 jam</b>, jadi data harian selalu ada walau belum disimpan. Cukup ubah unit yang Jalan, Rusak, Perbaikan, atau PM, lalu Simpan supaya tanggal itu tercatat sudah diisi petugas.</p>
<h3>Biar cepat</h3>
<ul>
    <li>Klik kotak lalu langsung ketik; isi lama otomatis terganti.</li>
    <li><kbd>Enter</kbd>/<kbd>↓</kbd> ke bawah, <kbd>↑</kbd> ke atas, <kbd>←</kbd><kbd>→</kbd> pindah kolom, <kbd>Esc</kbd> batal.</li>
    <li><b>Paste dari Excel</b>: salin beberapa baris/kolom, klik kotak awal, lalu <kbd>Ctrl</kbd>+<kbd>V</kbd>.</li>
    <li><b>Import</b>: unduh template, isi di Excel, unggah, periksa, lalu Simpan.</li>
    <li>Di HP, tiap unit tampil sebagai kartu dengan tombol <b>−</b> / <b>+</b> (tahan untuk cepat).</li>
    <li>Bila sinyal hilang, isian tetap tersimpan di perangkat; tekan Simpan saat sinyal kembali.</li>
</ul>
