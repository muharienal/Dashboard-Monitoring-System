<p class="lead-p">Berapa unit yang Jalan, Standby, dan Rusak rata-rata per hari, per jenis kendaraan.</p>
<h3>Arti angka</h3>
<dl>
    <dt>Rata-rata unit per hari</dt><dd>Jumlah unit-hari berstatus itu ÷ jumlah hari yang punya data, dibulatkan ke unit utuh.</dd>
    <dt>Utilisasi</dt><dd>Unit-hari berstatus Jalan ÷ seluruh unit-hari × 100%.</dd>
</dl>
<h3>Unduh</h3>
<ul><li><b>Excel</b>: pilih satu bulan atau beberapa bulan, dan bidang. Filter Jenis di halaman ikut dipakai.</li></ul>
