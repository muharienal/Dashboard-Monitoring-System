<p class="lead-p">Tabel rekap dan rincian jam per kendaraan.</p>
<h3>Isi</h3>
<dl>
    <dt>Rekap</dt><dd>Per bidang dan jenis: unit, total jam tiap status, Availability, Utilisasi. Baris Total dihitung ulang dari data, bukan menjumlahkan persen.</dd>
    <dt>Detail per kendaraan</dt><dd>Jam tiap status per tanggal (bila satu bulan dipilih) atau per bulan (bila satu tahun).</dd>
</dl>
<h3>Cara pakai</h3>
<ul><li><b>Excel</b> dan <b>Laporan PDF</b>: pilih satu bulan atau beberapa bulan (maks. 24), lalu bidang. Petugas bidang hanya bisa mengunduh bidangnya sendiri.</li></ul>
